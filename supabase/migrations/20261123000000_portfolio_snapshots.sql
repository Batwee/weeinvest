-- =============================================================================
-- Historique du portefeuille (WeeInvest)
-- -----------------------------------------------------------------------------
-- À exécuter dans Supabase -> SQL Editor (ou `supabase db push`).
-- Idempotent : peut être relancé sans casser l'existant.
--
-- Problème résolu : l'application ne connaît que le DERNIER cours connu
-- (asset_details.price), écrasé à chaque actualisation. Aucun historique de
-- valeur n'existe, donc aucune courbe de performance passée ne peut être
-- affichée sans l'inventer.
--
-- Principe : on enregistre une photo quotidienne du portefeuille, ce qui
-- construit progressivement un historique RÉEL. La courbe reste vide tant
-- qu'il n'y a pas au moins deux points : aucune performance passée n'est
-- simulée.
--
-- Grain : une ligne par (utilisateur, jour, devise, type de compte). Cette
-- maille permet de calculer des performances par devise et par enveloppe
-- (PEA / CTO) sans jamais additionner des montants de devises différentes.
-- =============================================================================

create table if not exists public.portfolio_snapshots (
  id_snapshot   bigint generated by default as identity primary key,
  id_user       uuid not null references auth.users (id) on delete cascade,
  snapshot_date date not null default current_date,
  currency      text not null,
  account_type  text not null check (account_type in ('PEA', 'CTO')),
  -- Valeur de marché = somme(quantité x dernier cours connu)
  market_value  numeric(18,2) not null default 0,
  -- Prix de revient = somme(quantité x prix moyen d'achat)
  cost_basis    numeric(18,2) not null default 0,
  created_at    timestamptz not null default now(),
  -- Une seule photo par jour et par (devise, compte) : permet un upsert idempotent
  unique (id_user, snapshot_date, currency, account_type)
);

comment on table public.portfolio_snapshots is
  'Photo quotidienne du portefeuille par devise et type de compte (valeur de marché + prix de revient). Sert à reconstruire une performance réelle, ajustée des apports/retraits.';

create index if not exists portfolio_snapshots_user_date_idx
  on public.portfolio_snapshots (id_user, snapshot_date desc);

alter table public.portfolio_snapshots enable row level security;

drop policy if exists "portfolio_snapshots_select_own" on public.portfolio_snapshots;
create policy "portfolio_snapshots_select_own"
  on public.portfolio_snapshots for select
  to authenticated
  using (id_user = auth.uid());

drop policy if exists "portfolio_snapshots_insert_own" on public.portfolio_snapshots;
create policy "portfolio_snapshots_insert_own"
  on public.portfolio_snapshots for insert
  to authenticated
  with check (id_user = auth.uid());

drop policy if exists "portfolio_snapshots_update_own" on public.portfolio_snapshots;
create policy "portfolio_snapshots_update_own"
  on public.portfolio_snapshots for update
  to authenticated
  using (id_user = auth.uid())
  with check (id_user = auth.uid());

drop policy if exists "portfolio_snapshots_delete_own" on public.portfolio_snapshots;
create policy "portfolio_snapshots_delete_own"
  on public.portfolio_snapshots for delete
  to authenticated
  using (id_user = auth.uid());
