-- =============================================================================
-- Positions boursières détenues (WeeInvest)
-- -----------------------------------------------------------------------------
-- À exécuter dans Supabase -> SQL Editor (ou `supabase db push`).
-- Idempotent : peut être relancé sans casser l'existant.
--
-- Principe : asset_details reste le référentiel commun des entreprises
-- (watchlist ET positions). Deux notions restent distinctes :
--   * suit une entreprise  -> asset_details.is_followed = true  (watchlist)
--   * détient une position -> ligne dans public.stock_positions
-- Détenir une entreprise ne l'ajoute donc pas à la watchlist, et inversement.
-- =============================================================================

-- 1. Référentiel : distinguer « suivie » de « simplement référencée »,
--    et mémoriser le dernier cours connu (cache communautaire, comme RSI/SMA).
alter table public.asset_details
  add column if not exists is_followed boolean not null default true;

alter table public.asset_details
  add column if not exists price numeric;

alter table public.asset_details
  add column if not exists price_updated_at timestamptz;

comment on column public.asset_details.is_followed is
  'true = entreprise suivie (visible dans la watchlist) ; false = référencée uniquement par une position';
comment on column public.asset_details.price is
  'Dernier cours connu (cache communautaire, source Alpha Vantage GLOBAL_QUOTE)';
comment on column public.asset_details.price_updated_at is
  'Horodatage du dernier cours récupéré';

-- 2. Positions réellement détenues par l'utilisateur.
create table if not exists public.stock_positions (
  id_position  bigint generated by default as identity primary key,
  id_user      uuid not null references auth.users (id) on delete cascade,
  id_asset     bigint not null references public.asset_details (id_asset) on delete cascade,
  -- PEA ou CTO
  account_type text not null check (account_type in ('PEA', 'CTO')),
  quantity     numeric(18,6) not null check (quantity > 0),
  avg_price    numeric(18,6) not null check (avg_price >= 0),
  -- Saisie manuelle : aucun montant n'est déduit automatiquement
  currency     text not null default 'EUR',
  -- Place de cotation (informative, ex : NYSE, Euronext Paris)
  exchange     text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  -- Anti-doublon : une seule position par (entreprise, compte)
  unique (id_user, id_asset, account_type)
);

comment on table public.stock_positions is
  'Positions boursières détenues (quantité et prix moyen saisis manuellement)';

create index if not exists stock_positions_user_idx on public.stock_positions (id_user);
create index if not exists stock_positions_asset_idx on public.stock_positions (id_asset);

alter table public.stock_positions enable row level security;

drop policy if exists "stock_positions_select_own" on public.stock_positions;
create policy "stock_positions_select_own"
  on public.stock_positions for select
  to authenticated
  using (id_user = auth.uid());

drop policy if exists "stock_positions_insert_own" on public.stock_positions;
create policy "stock_positions_insert_own"
  on public.stock_positions for insert
  to authenticated
  with check (id_user = auth.uid());

drop policy if exists "stock_positions_update_own" on public.stock_positions;
create policy "stock_positions_update_own"
  on public.stock_positions for update
  to authenticated
  using (id_user = auth.uid())
  with check (id_user = auth.uid());

drop policy if exists "stock_positions_delete_own" on public.stock_positions;
create policy "stock_positions_delete_own"
  on public.stock_positions for delete
  to authenticated
  using (id_user = auth.uid());
