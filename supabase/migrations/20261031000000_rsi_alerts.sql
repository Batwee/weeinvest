-- =============================================================================
-- Alertes RSI Weekly automatiques (WeeInvest)
-- -----------------------------------------------------------------------------
-- À exécuter dans Supabase -> SQL Editor (ou `supabase db push`).
-- Idempotent : peut être relancé sans casser l'existant.
--
-- Rappel : asset_details.alerte (boolean, default false) existe déjà et reste
-- la source de vérité pour déterminer quels actifs sont surveillés.
-- Les valeurs RSI / SMA / conclusion / RSI_SMA_updated_at existantes sont
-- réutilisées : aucune colonne dupliquée.
-- =============================================================================

-- 1) État d'alerte courant de l'actif : null = neutre, 'oversold' = survente,
--    'overbought' = surachat. Sert à ne pas renvoyer de notification en double.
alter table public.asset_details
  add column if not exists alert_state text;

comment on column public.asset_details.alert_state is
  'Dernier état RSI notifié : null (neutre), oversold (<35), overbought (>70)';

-- Sécurise le champ alerte s'il n'a pas encore été créé
alter table public.asset_details
  add column if not exists alerte boolean not null default false;

-- Accélère la récupération des actifs surveillés par le cron
create index if not exists asset_details_alerte_idx
  on public.asset_details (alerte)
  where alerte = true;

-- 2) Abonnements Push des utilisateurs (une ligne par appareil/navigateur)
create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  id_user uuid not null references auth.users (id) on delete cascade,
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  created_at timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;

drop policy if exists "push_subscriptions_select_own" on public.push_subscriptions;
create policy "push_subscriptions_select_own"
  on public.push_subscriptions for select
  to authenticated
  using (id_user = auth.uid());

drop policy if exists "push_subscriptions_insert_own" on public.push_subscriptions;
create policy "push_subscriptions_insert_own"
  on public.push_subscriptions for insert
  to authenticated
  with check (id_user = auth.uid());

drop policy if exists "push_subscriptions_delete_own" on public.push_subscriptions;
create policy "push_subscriptions_delete_own"
  on public.push_subscriptions for delete
  to authenticated
  using (id_user = auth.uid());

-- 3) Historique des notifications envoyées (anti-doublon + traçabilité)
create table if not exists public.rsi_alert_history (
  id bigint generated by default as identity primary key,
  id_asset bigint,
  id_user uuid not null,
  symbol text not null,
  asset_name text,
  rsi numeric,
  signal text not null,      -- 'oversold' | 'overbought'
  threshold integer not null, -- 35 | 70
  sent_at timestamptz not null default now()
);

create index if not exists rsi_alert_history_user_idx
  on public.rsi_alert_history (id_user, sent_at desc);

alter table public.rsi_alert_history enable row level security;

drop policy if exists "rsi_alert_history_select_own" on public.rsi_alert_history;
create policy "rsi_alert_history_select_own"
  on public.rsi_alert_history for select
  to authenticated
  using (id_user = auth.uid());

-- 4) Verrou d'exécution du cron (évite deux exécutions simultanées).
--    Aucune policy : accessible uniquement via la service role (Edge Function).
create table if not exists public.rsi_alert_runs (
  id bigint generated by default as identity primary key,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running', -- 'running' | 'done' | 'error'
  processed integer default 0,
  requests integer default 0,
  detail text
);

alter table public.rsi_alert_runs enable row level security;
